$host = "localhost";
$username = "root";
$password = "";
$database = "multiplication_test";

/*
|--------------------------------------------------------------------------
| Create Connection
|--------------------------------------------------------------------------
*/

$conn = new mysqli($host, $username, $password, $database);

/*
|--------------------------------------------------------------------------
| Check Connection
|--------------------------------------------------------------------------
*/

