    die("Database Connection Failed: " . $conn->connect_error);
}

/*
|--------------------------------------------------------------------------
| Character Set
|--------------------------------------------------------------------------
*/

$conn->set_charset("utf8mb4");

/*
|--------------------------------------------------------------------------
| Helper Function (Optional)
|--------------------------------------------------------------------------
*/

function sanitize($data)
{
    return htmlspecialchars(trim($data), ENT_QUOTES, 'UTF-8');
}
